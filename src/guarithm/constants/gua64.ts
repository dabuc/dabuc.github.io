// ============================================
// 查询索引构建 (提升查询性能)
// ============================================

/** 按编码查找的Map */
export const GUA64_BY_CODE: ReadonlyMap<string, Gua64Record> = new Map(
  GUA64_DATA.map(g => [g.编码, g])
);

/** 按卦名查找的Map */
export const GUA64_BY_NAME: ReadonlyMap<string, Gua64Record> = new Map(
  GUA64_DATA.map(g => [g.卦名, g])
);

/** 按卦序查找的Map */
export const GUA64_BY_SEQUENCE: ReadonlyMap<number, Gua64Record> = new Map(
  GUA64_DATA.map(g => [g.卦序, g])
);

/** 按卦宫分组 */
export const GUA64_BY_GONG: ReadonlyMap<string, readonly Gua64Record[]> = (() => {
  const map = new Map<string, Gua64Record[]>();
  for (const gua of GUA64_DATA) {
    const list = map.get(gua.宫名) || [];
    list.push(gua);
    map.set(gua.宫名, list);
  }
  return map;
})();

/** 查找本宫卦 (八纯卦) */
export function getBenGongGua(gongName: string): Gua64Record | undefined {
  const gongGua = GUA64_BY_GONG.get(gongName);
  return gongGua?.find(g => g.卦次 === '本宫');
}